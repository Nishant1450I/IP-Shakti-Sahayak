import { retrieveEvidence } from '../../src/services/ragEngine.js';
import { getLLMProvider } from './llm/index.js';

/**
 * RAG Service layer for server handling query execution.
 * 
 * Orchestrates the pipeline:
 *   1. Run existing retrieval engine (unchanged) → sources, confidence, fallback answer
 *   2. If insufficient evidence → return existing insufficient response (no LLM call)
 *   3. Otherwise → call the configured LLM provider (Gemini) with retrieved evidence
 *   4. Override answerSummary with LLM output; keep sources/confidence/recommendations
 *   5. If LLM fails → fall back to the existing template answer so the app never breaks
 */

const LEGAL_DISCLAIMER =
  'Information is for educational purposes only, not legal advice. ' +
  'This decision-support information is retrieved from a verified legal corpus ' +
  'and generated by an AI assistant for preliminary evaluation. ' +
  'Always consult a certified Indian Patent Attorney, Registered Trade Mark Agent, ' +
  'or State Licensing Authority (AYUSH) prior to commercial manufacturing or patent submission.';

export async function executeQuery({
  query = '',
  productName = '',
  ingredients = '',
  intendedUse = '',
  description = '',
  concern = 'patent',
  jurisdiction = 'India',
  language = 'en',
  classification = ''
} = {}) {
  // 1. Execute RAG engine retrieval over verified corpus (unchanged)
  const retrievalResult = retrieveEvidence({
    query,
    productName,
    ingredients,
    intendedUse,
    description,
    concern,
    jurisdiction
  });

  // 2. Preserve existing insufficient-evidence behavior — no LLM call
  if (retrievalResult.isInsufficient) {
    return {
      ...retrievalResult,
      disclaimer: LEGAL_DISCLAIMER,
      generatedBy: 'retrieval-only'
    };
  }

  // 3. Build evidence context from retrieved sources
  const evidenceContext = (retrievalResult.sources || []).map((src, idx) => {
    return [
      `[Source ${idx + 1}]`,
      `Title: ${src.title}`,
      `Authority: ${src.authority}`,
      `Section: ${src.section}`,
      `Clause: ${src.clause}`,
      `Snippet: ${src.snippet}`,
      `URL: ${src.source_url}`,
      `Verification: ${src.verification_status}`
    ].join('\n');
  }).join('\n\n');

  // 4. Build the LLM prompt
  const systemInstruction = [
    'You are IP-SAKTI SAHAYAK, an AI decision-support assistant for Ayurvedic intellectual property and regulatory guidance.',
    '',
    'STRICT RULES:',
    '1. Answer ONLY from the supplied evidence sources. Do NOT use any outside knowledge.',
    '2. If the supplied evidence is insufficient to answer the question, clearly state that you cannot establish the answer from the available sources.',
    '3. NEVER invent laws, sections, rules, treaties, URLs, or citations that are not present in the supplied evidence.',
    '4. Cite sources inline using [Source N] markers that correspond to the numbered evidence sources provided.',
    '5. Be concise, plain-language, and practical. Structure the answer for a non-lawyer Ayurvedic entrepreneur.',
    '6. End with the disclaimer: "Information is for educational purposes only, not legal advice."'
  ].join('\n');

  const prompt = [
    `Product Name: ${productName || 'Not provided'}`,
    `Ingredients: ${ingredients || 'Not provided'}`,
    `Intended Use: ${intendedUse || 'Not provided'}`,
    `Description: ${description || 'Not provided'}`,
    `Legal Concern Focus: ${concern}`,
    `Jurisdiction: ${jurisdiction}`,
    `Classification: ${classification || 'Not provided'}`,
    '',
    '=== RETRIEVED EVIDENCE (use ONLY this) ===',
    evidenceContext,
    '',
    '=== QUESTION ===',
    `Based ONLY on the retrieved evidence above, provide a plain-language assessment for this Ayurvedic product regarding ${concern} in ${jurisdiction}. Include inline [Source N] citations. If the evidence is insufficient, say so explicitly.`
  ].join('\n');

  // 5. Call the configured LLM provider (Gemini) with fallback to template answer
  try {
    const provider = getLLMProvider();
    const { text } = await provider.generateAnswer({
      systemInstruction,
      prompt
    });

    return {
      ...retrievalResult,
      answerSummary: text,
      disclaimer: LEGAL_DISCLAIMER,
      generatedBy: 'gemini'
    };
  } catch (error) {
    console.error('[RAG Service] LLM generation failed, falling back to template answer:', error.message);

    return {
      ...retrievalResult,
      answerSummary: retrievalResult.answerSummary,
      disclaimer: LEGAL_DISCLAIMER,
      generatedBy: 'template-fallback',
      llmError: error.message
    };
  }
}